def compute_quality():
    """
    Расчет среднего эмпирического риска Q, т.е. среднего от loss о всей обучающей выборке
    """
    np.random.seed(0)  # псевдослучайные числа образуют одну и ту же последовательность (при каждом запуске)
    x = np.arange(-1.0, 1.0, 0.1)  # аргумент [-1; 1] с шагом 0,1
    w = [0.5, -0.3]  # коэффициенты модели

    model = lambda x, w: (w[0] + w[1] * x)  # модель

    loss = lambda ax, y: (ax - y) ** 2  # квадратическая функция потерь

    y = model(x, w) + np.random.normal(0, 0.1, len(x))  # вектор целевых значений

    # Вычисляем значение среднего эмпирического риска
    Q = reduce(operator.add, loss(model(x, w), y)) / len(x)
    print(Q)


