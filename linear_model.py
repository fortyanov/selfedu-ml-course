def binary_classification():
    """
    https://stepik.org/lesson/1370053/step/8?unit=1386243
    Классификация точек на двумерном пространстве через трехмерную линейную модель
    где первый вес w[0] нужен для того чтобы прямая проходила через начало координат
    """
    x_test = [(5, -3), (-3, 8), (3, 6), (0, 0), (5, 3), (-3, -1),
              (-3, 3)]  # точки для которых нужно определить класс в двумерном пространстве
    w = [2.5, -0.68, -0.98]  # коэффициенты модели

    x_test_3d = [(1, xi[0], xi[1]) for xi in x_test]  # переносим точки в трехмерное пространство

    predict = [int(np.sign(np.array(w).T @ np.array(xi))) for xi in x_test_3d]
    print(predict)


def compute_margin():
    """
    Расчет расстояния точек от разделяющей гиперплоскости
    """
    w = np.array([15 / 7, -9 / 7, -1])
    x_test = [[1, -8, -4], [1, -2, 2], [1, 4, 8], [1, 6, 3]]  # точки для которых нужно рассчитать расстояния
    y_test = [1, 1, -1, -1]

    model = lambda x: w[0] + w[1] * x[1] + w[2] * x[2]

    margin = [model(xi) * yi for xi, yi in zip(x_test, y_test)]
    print(margin)


def compute_quality1():
    """
    Расчет показателя качества для линейной модели классификации путем подсчета количества неправильных классификаций
    """
    w = np.array([-8 / 3, -2 / 3, 1])
    x_test = np.array([(-5, 2), (-4, 6), (3, 2), (3, -3), (5, 5), (5, 2), (-1, 3)])
    y_test = np.array([1, 1, 1, -1, -1, -1, -1])

    x_test_3d = np.array([(1, *xi) for xi in x_test])

    model = lambda w, x: w.T @ x

    Q = reduce(operator.add, [0 if (model(w, xi) * yi * -1) < 0 else 1 for xi, yi in zip(x_test_3d, y_test)])
    print(Q)


def compute_quality2():
    """
    Расчет показателя качества между некоторой функции func и полиномиальной модели ее имитирующей путем расчета квадратичной ошибки
    """

    def func(x):
        return 0.1 * x ** 2 - np.sin(x) + 0.1 * np.cos(x * 5) + 1.

    def loss(predicted, actual):
        return (predicted - actual) ** 2

    def model(x):
        return 1.11 + -0.26 * x + 0.061 * x ** 2 + 0.0226 * x ** 3 + 0.00178 * x ** 4

    coord_x = np.arange(-5.0, 5.0, 0.1)  # значения отсчетов по оси абсцисс

    Q = np.sum([loss(model(x), func(x)) for x in coord_x]) / len(coord_x)
    print(Q)


